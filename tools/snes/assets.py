#!/usr/bin/env python3
"""
Extract and convert what the SNES build needs from the Genesis ROM.

usage: assets.py ROM OUTDIR

Writes OUTDIR/assets.s (the data, assembled into the SNES ROM) and
OUTDIR/assets.inc (its labels). Nothing taken from the ROM is committed;
it all comes from here at build time.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nemesis  # noqa: E402


def words(rom, addr, count):
    """Big-endian words from the ROM, for the SNES's little-endian ones."""
    return list(struct.unpack_from('>%dH' % count, rom, addr))


def planar_lut():
    """For each byte of a Genesis 4bpp row (two pixels, the left one in the
    high nibble) at each of the four places in the row: its bits in SNES
    planes 0-3, as the bytes p0 p1 p2 p3 of a planar row."""
    out = bytearray()
    for place in range(4):
        for b in range(256):
            planes = [0, 0, 0, 0]
            for half, pixel in ((0, b >> 4), (1, b & 15)):
                x = place * 2 + half
                for p in range(4):
                    planes[p] |= ((pixel >> p) & 1) << (7 - x)
            out += bytes(planes)
    return bytes(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rom = open(sys.argv[1], 'rb').read()
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)

    bins = {
        'logo_bitmap': nemesis.decode(rom, 0x020A56),    # the SEGA logo, 49 tiles
        'planar_lut': planar_lut(),
    }
    tables = {
        'logo_first_walker': words(rom, 0x008142, 4),    # x, y, offset, direction
        'logo_sweep_colours': words(rom, 0x00814A, 24),  # 8 steps of 3 colours
    }

    for name, data in bins.items():
        with open(os.path.join(out, name + '.bin'), 'wb') as f:
            f.write(data)
    with open(os.path.join(out, 'assets.s'), 'w') as f:
        f.write('; Generated by tools/snes/assets.py from the Genesis ROM\n')
        f.write('.include "assets.inc"\n\n.segment "ASSETS"\n')
        for name in bins:
            f.write('%s: .incbin "%s.bin"\n' % (name, name))
        for name, values in tables.items():
            f.write('%s:\n' % name)
            for k in range(0, len(values), 8):
                f.write('    .word %s\n' % ', '.join('$%04X' % v for v in values[k:k + 8]))
    with open(os.path.join(out, 'assets.inc'), 'w') as f:
        f.write('; Generated by tools/snes/assets.py\n')
        for name in list(bins) + list(tables):
            f.write('.global %s\n' % name)


if __name__ == '__main__':
    main()
