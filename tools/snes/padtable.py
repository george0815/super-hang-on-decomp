#!/usr/bin/env python3
"""
A pad table for a test build of the SNES port: from a pad log of the
native port (livetest SHO_PADLOG: game frame, pad per read), the pad the
game read first in each game frame (or the one before, if none), so the
SNES game can read its input by game frame itself (snes/rt.s, PADTABLE).

usage: padtable.py PADLOG OUT.s
"""
import sys

reads = []
for line in open(sys.argv[1]):
    g, v = line.split()
    reads.append((int(g), int(v, 16)))
last = max(g for g, _ in reads) if reads else 0
table = []
k = 0
value = 0
for g in range(last + 1):
    while k < len(reads) and reads[k][0] < g:
        value = reads[k][1]
        k += 1
    if k < len(reads) and reads[k][0] == g:
        value = reads[k][1]          # the first read in this frame
    table.append(value)
with open(sys.argv[2], 'w') as f:
    f.write('; Generated by tools/snes/padtable.py\n.export pad_table, pad_table_end\n')
    f.write('.segment "ASSETS"\npad_table:\n')
    for i in range(0, len(table), 16):
        f.write('    .byte %s\n' % ', '.join('$%02X' % v for v in table[i:i + 16]))
    f.write('pad_table_end:\n')
